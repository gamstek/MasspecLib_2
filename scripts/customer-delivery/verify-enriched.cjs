const cmp=(a,b,label)=>{
 if(typeof b==='number'){assert.ok(a!=null&&Number.isFinite(Number(a))&&Math.abs(Number(a)-b)<=Math.max(0.0001,Math.abs(b)*2e-7),label+': '+a+' vs '+b);return}
 assert.deepEqual(a,b,label)
}
function literal(v){
 if(v==null)return 'NULL'
 if(typeof v==='number') {assert.ok(Number.isFinite(v));return String(v)}
 if(typeof v==='boolean')return v?'1':'0'
 if(v instanceof Date){
  const pad=(n,w=2)=>String(n).padStart(w,'0')
  v=v.getFullYear()+'-'+pad(v.getMonth()+1)+'-'+pad(v.getDate())+' '+pad(v.getHours())+':'+pad(v.getMinutes())+':'+pad(v.getSeconds())+'.'+pad(v.getMilliseconds(),3)
 }
 else if(typeof v==='object')v=JSON.stringify(v)
 if(v==='')return "''"
 return "CONVERT(0x"+Buffer.from(String(v),'utf8').toString('hex')+" USING utf8mb4)"
}
async function snapshot(c,database){
 const result={}
 for(const table of tableNames){
  const [rows,fields]=await c.query('SELECT * FROM '+ident(database)+'.'+ident(table)+' ORDER BY 1')
  result[table]={columns:fields.map(f=>f.name),rows}
 }
 return result
}
async function exportSql(c,database,file,snap){
 let parts=['-- MasspecLib2 native schema 4. Generated by the native MSLDATA importer.', '-- Alternative format of the same library: import SQL OR MSLDATA, not both.', 'SET NAMES utf8mb4;','SET FOREIGN_KEY_CHECKS=0;']
 for(const table of tableNames){
  const [ddl]=await c.query('SHOW CREATE TABLE '+ident(database)+'.'+ident(table))
  parts.push(ddl[0]['Create Table']+';')
 }
 for(const table of tableNames){
  const {columns,rows}=snap[table]
  for(const row of rows)parts.push('INSERT INTO '+ident(table)+' ('+columns.map(ident).join(',')+') VALUES ('+columns.map(k=>literal(row[k])).join(',')+');')
 }
 parts.push('SET FOREIGN_KEY_CHECKS=1;','')
 fs.writeFileSync(file,parts.join('\n'))
}
async function comparePackage(c,database,pkg,meta){
 const snap=await snapshot(c,database)
 assert.equal(snap.compounds.rows.length,meta.rowCount)
 assert.equal(snap.ms_methods.rows.length,meta.msMethodCount)
 assert.equal(snap.lc_methods.rows.length,meta.lcMethodCount)
 assert.equal(snap.lc_methods_items.rows.length,meta.gradientStepCount)
 assert.equal(snap.detection_profiles.rows.length,meta.profileCount)
 assert.equal(snap.spectra.rows.length,0)
 assert.equal(snap.source_records.rows.length,meta.rowCount)
 assert.equal(snap.classes.rows.length,Object.keys(meta.sourceCategories).length)
 let fieldChecks=0
 for(const group of pkg.groups){
  const rec=snap.source_records.rows.find(r=>r.source_key===group.source.key);assert.ok(rec)
  assert.deepEqual(json(rec.raw),group)
  const links=snap.entity_sources.rows.filter(x=>x.source_record_id===rec.id)
  const one=type=>{const l=links.filter(x=>x.entity_type===type);assert.equal(l.length,1);return l[0].entity_id}
  const compound=snap.compounds.rows.find(x=>x.id===one('compound'))
  for(const [k,v] of Object.entries(group.compound)){cmp(['name','properties','identifiers'].includes(k)?json(compound[k]):compound[k],v,'compound '+group.source.key+' '+k);fieldChecks++}
  const methods=links.filter(x=>x.entity_type==='ms_method').map(l=>snap.ms_methods.rows.find(x=>x.id===l.entity_id)).sort((a,b)=>a.id-b.id)
  assert.equal(methods.length,group.methods.length)
  for(const [i,m] of group.methods.entries())for(const [k,v] of Object.entries(m))if(k!=='localId'){
   cmp(k==='conditions'?json(methods[i][k]):methods[i][k],v,'method '+group.source.key+' '+k);fieldChecks++
  }
  const lc=snap.lc_methods.rows.find(x=>x.id===one('lc_method'))
  for(const [k,v] of Object.entries(group.lcMethods[0]))if(!['localId','items'].includes(k)){
   cmp(k==='conditions'?json(lc[k]):lc[k],v,'lc '+group.source.key+' '+k);fieldChecks++
  }
  const steps=snap.lc_methods_items.rows.filter(x=>x.lc_methods_id===lc.id).sort((a,b)=>a.step_order-b.step_order)
  assert.equal(steps.length,group.lcMethods[0].items.length)
  for(const [i,s] of group.lcMethods[0].items.entries())for(const [k,v] of Object.entries(s)){cmp(steps[i][k],v,'step '+group.source.key+' '+k);fieldChecks++}
  const profile=snap.detection_profiles.rows.find(x=>x.id===one('detection_profile'))
  assert.deepEqual(json(profile.data),group.profiles[0].data)
 }
 return {snapshot:snap,fieldChecks}
}
